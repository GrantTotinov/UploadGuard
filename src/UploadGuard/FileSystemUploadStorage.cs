using System.Security.Cryptography;
using System.Text.RegularExpressions;

namespace UploadGuard;

/// <summary>
/// Stores files in a folder under random names (128 bits) with the detected type's extension. Names from clients
/// are never used, so there is nothing to traverse, overwrite or execute.
/// </summary>
public sealed partial class FileSystemUploadStorage : IUploadStorage
{
    /// <summary>Initializes a new instance and creates the folder if needed.</summary>
    /// <param name="root">The folder. Keep it outside the web root and give the app user no execute permission on it.</param>
    public FileSystemUploadStorage(string root)
    {
        ArgumentException.ThrowIfNullOrEmpty(root);
        Root = Path.GetFullPath(root);
        Directory.CreateDirectory(Root);
    }

    /// <summary>Gets the full path of the folder.</summary>
    public string Root { get; }

    /// <inheritdoc />
    public async Task<string> SaveAsync(Stream content, FileType type, CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(content);
        ArgumentNullException.ThrowIfNull(type);
        var name = RandomNumberGenerator.GetHexString(32, lowercase: true) + type.Extensions[0];
        var path = Path.Combine(Root, name);
        var file = new FileStream(path, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true);
        try
        {
            await using (file)
            {
                await content.CopyToAsync(file, cancellationToken);
            }
        }
        catch
        {
            File.Delete(path);
            throw;
        }

        return name;
    }

    /// <inheritdoc />
    public Task<Stream> OpenReadAsync(string name, CancellationToken cancellationToken = default) =>
        Task.FromResult<Stream>(new FileStream(PathOf(name), FileMode.Open, FileAccess.Read, FileShare.Read, 81920, useAsync: true));

    /// <inheritdoc />
    public Task DeleteAsync(string name, CancellationToken cancellationToken = default)
    {
        File.Delete(PathOf(name));
        return Task.CompletedTask;
    }

    internal static FileSystemUploadStorage Create(string root, string? webRoot)
    {
        var full = Path.GetFullPath(root);
        if (webRoot is not null)
        {
            var web = Path.TrimEndingDirectorySeparator(Path.GetFullPath(webRoot));
            if (full.Equals(web, StringComparison.OrdinalIgnoreCase)
                || full.StartsWith(web + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase))
            {
                throw new InvalidOperationException(
                    $"UploadGuard StoragePath '{full}' is inside the web root '{web}', where uploaded files could be served or executed. Choose a folder outside it.");
            }
        }

        return new FileSystemUploadStorage(full);
    }

    // Only names this class generated: no separators, no "..", nothing to traverse with.
    private string PathOf(string name) =>
        name is not null && StoredName().IsMatch(name)
            ? Path.Combine(Root, name)
            : throw new ArgumentException("Not a name generated by FileSystemUploadStorage.", nameof(name));

    [GeneratedRegex("^[0-9a-f]{32}\\.[a-z0-9]{1,8}$")]
    private static partial Regex StoredName();
}
