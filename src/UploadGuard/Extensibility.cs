namespace UploadGuard;

/// <summary>
/// Scans accepted content, for example with an antivirus engine. Register implementations in dependency injection;
/// all of them run, in registration order, after the built-in checks.
/// </summary>
public interface IUploadScanner
{
    /// <summary>Scans the content. Throw <see cref="UploadRejectedException"/> to reject it.</summary>
    /// <param name="content">The content, positioned at the start.</param>
    /// <param name="type">The detected type.</param>
    /// <param name="cancellationToken">Cancels the scan.</param>
    /// <returns>A task that completes when the content is clean.</returns>
    /// <remarks>Any other exception rejects the file with <see cref="UploadErrorCode.ScanFailed"/>: uploads fail closed.</remarks>
    Task ScanAsync(Stream content, FileType type, CancellationToken cancellationToken);
}

/// <summary>Rewrites accepted content before it is stored. Add one with <see cref="UploadPolicy.Transform"/>.</summary>
public interface IUploadTransformer
{
    /// <summary>Writes new content to <paramref name="output"/>, or returns null to keep the input unchanged.</summary>
    /// <param name="input">The content, positioned at the start.</param>
    /// <param name="type">The type of the input.</param>
    /// <param name="output">An empty stream for the new content.</param>
    /// <param name="cancellationToken">Cancels the transform.</param>
    /// <returns>The type of the output, or null when nothing was written.</returns>
    /// <exception cref="UploadRejectedException">The content cannot be transformed and must be rejected.</exception>
    Task<FileType?> TransformAsync(Stream input, FileType type, Stream output, CancellationToken cancellationToken);
}

/// <summary>Stores accepted files under generated names.</summary>
public interface IUploadStorage
{
    /// <summary>Stores the content under a new random name.</summary>
    /// <param name="content">The content, positioned at the start.</param>
    /// <param name="type">The type; its first extension ends the name.</param>
    /// <param name="cancellationToken">Cancels the write.</param>
    /// <returns>The generated name, for example <c>3f9c…e1.jpg</c>.</returns>
    Task<string> SaveAsync(Stream content, FileType type, CancellationToken cancellationToken = default);

    /// <summary>Opens a stored file.</summary>
    /// <param name="name">A name returned by <see cref="SaveAsync"/>.</param>
    /// <param name="cancellationToken">Cancels the open.</param>
    /// <returns>The content; dispose it.</returns>
    /// <exception cref="ArgumentException">The name was not generated by this storage.</exception>
    Task<Stream> OpenReadAsync(string name, CancellationToken cancellationToken = default);

    /// <summary>Deletes a stored file. Does nothing when it does not exist.</summary>
    /// <param name="name">A name returned by <see cref="SaveAsync"/>.</param>
    /// <param name="cancellationToken">Cancels the delete.</param>
    /// <returns>A task that completes when the file is gone.</returns>
    /// <exception cref="ArgumentException">The name was not generated by this storage.</exception>
    Task DeleteAsync(string name, CancellationToken cancellationToken = default);
}
